import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { tempRoot, writeApprovedIdentity, readyRuntimePatch } from '../helpers.ts';
import { Host } from '../../apps/host/src/app-context.ts';
import { buildConfig } from '../../apps/host/src/config/schema.ts';

test('重试 HTTP：鉴权/修订门、消息状态快照、同键回执、终态重放不产生虚假 started', async t => {
  const root = tempRoot('message-retry-http-');
  writeApprovedIdentity(root);
  const config = buildConfig({ ...readyRuntimePatch(), deployment: { port: 0 }, runtime: { ...readyRuntimePatch().runtime, provider: 'mock' } });
  const host = await Host.create({ stateRoot: root, config, logDir: null, bind: '127.0.0.1', port: 0 });
  const queued: string[] = [];
  // HTTP contract test: enqueue is observed; no model (even mock) is executed.
  host.supervisor.enqueue = id => { queued.push(id); };
  await host.start();
  t.after(async () => { await host.stop(); fs.rmSync(root, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${host.port}`;
  const token = fs.readFileSync(path.join(root, 'config/auth.token'), 'utf8').trim();
  const headers = { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', Origin: base };
  host.db.prepare("INSERT INTO windows(id,conversation_id,status,created_at,updated_at) VALUES ('w-retry','primary','ACTIVE','now','now')").run();
  host.db.prepare("UPDATE conversations SET active_window_id='w-retry' WHERE id='primary'").run();
  host.db.prepare("INSERT INTO window_trajectories(window_id,messages_json,manifest_json,updated_at) VALUES ('w-retry','[]','[]','now')").run();
  const sent = host.messages.submitUserMessageWithTurn({ conversationId: 'primary', content: 'before', clientMessageId: 'retry-http' });
  host.db.prepare("UPDATE turns SET state='failed',completed_at='now' WHERE id=?").run(sent.turnId);
  host.db.prepare("UPDATE attempts SET state='failed',window_id='w-retry',blocked_reason='OR_NETWORK_ERROR',completed_at='now' WHERE id=?").run(sent.attemptId);
  const messageUrl = `${base}/api/v1/conversations/primary/messages/${sent.message.id}`;
  const body = JSON.stringify({ content: 'after' });
  const retryHeaders = { ...headers, 'If-Match': '"1"', 'Idempotency-Key': 'http-retry-1' };
  assert.equal((await fetch(messageUrl + '/retry', { method: 'POST', body })).status, 401);
  assert.equal((await fetch(messageUrl + '/retry', { method: 'POST', headers, body })).status, 400);
  assert.equal((await fetch(messageUrl + '/retry', { method: 'POST', headers: { ...headers, 'Idempotency-Key': 'missing-rev' }, body })).status, 428);
  const fresh = await (await fetch(messageUrl, { headers })).json() as any;
  assert.equal(fresh.message.reply_status.can_retry, true);
  const list = await (await fetch(`${base}/api/v1/conversations/primary/messages`, { headers })).json() as any;
  assert.equal(list.messages.find((m: any) => m.id === sent.message.id).reply_status.can_retry, true);
  const wrongRevision = await fetch(messageUrl + '/retry', { method: 'POST', headers: { ...retryHeaders, 'If-Match': '"2"', 'Idempotency-Key': 'wrong-rev' }, body });
  assert.equal(wrongRevision.status, 409);
  assert.equal(((await wrongRevision.json()) as any).error.code, 'revision_conflict');
  const firstResponse = await fetch(messageUrl + '/retry', { method: 'POST', headers: retryHeaders, body });
  assert.equal(firstResponse.status, 202);
  const first = await firstResponse.json() as any;
  assert.equal(first.message.current_revision, 2);
  assert.equal(first.message.reply_status.state, 'pending');
  assert.equal(first.turn_id, sent.turnId);
  assert.equal(queued.length, 1);
  assert.equal((host.db.prepare('SELECT COUNT(*) n FROM attempts WHERE turn_id=?').get(sent.turnId) as { n: number }).n, 2);
  const second = await fetch(messageUrl + '/retry', { method: 'POST', headers: { ...retryHeaders, 'If-Match': '"2"', 'Idempotency-Key': 'second-click' }, body });
  assert.equal(second.status, 409);
  assert.equal(((await second.json()) as any).error.code, 'RETRY_NOT_FAILED');
  // Simulate terminal completion followed by a lost-event gap. Receipt replay
  // must return current state without a phantom spinner or another enqueue.
  host.db.prepare("UPDATE turns SET state='completed',completed_at='later' WHERE id=?").run(sent.turnId);
  host.db.prepare("UPDATE attempts SET state='completed',completed_at='later' WHERE id=?").run(first.attempt_id);
  host.db.prepare('DELETE FROM runtime_stream_events WHERE attempt_id=?').run(first.attempt_id);
  const replayResponse = await fetch(messageUrl + '/retry', { method: 'POST', headers: retryHeaders, body });
  assert.equal(replayResponse.status, 200);
  const replay = await replayResponse.json() as any;
  assert.equal(replay.duplicate, true);
  assert.equal(replay.attempt_id, first.attempt_id);
  assert.equal(replay.message.reply_status.state, 'completed');
  assert.equal(queued.length, 1);
  assert.equal((host.db.prepare("SELECT COUNT(*) n FROM runtime_stream_events WHERE attempt_id=? AND kind='turn.started'").get(first.attempt_id) as { n: number }).n, 0);
  assert.equal((host.db.prepare('SELECT COUNT(*) n FROM provider_requests').get() as { n: number }).n, 0);
  const conflict = await fetch(messageUrl + '/retry', { method: 'POST', headers: retryHeaders, body: JSON.stringify({ content: 'different request' }) });
  assert.equal(conflict.status, 409);
  assert.equal(((await conflict.json()) as any).error.code, 'idempotency_conflict');
  const saved = await fetch(messageUrl, { method: 'PUT', headers: { ...headers, 'If-Match': '"2"' }, body: JSON.stringify({ content: 'saved revision' }) });
  assert.equal(saved.status, 200);
  assert.equal(((await saved.json()) as any).message.reply_status.state, 'completed');
  assert.equal(queued.length, 1);
});
